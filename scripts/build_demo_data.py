import argparse
import os
import sys
from datetime import timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from marketintel import SAMPLE_DIR
from marketintel.datasource import EXPORTS, DbSource
from scripts.load_sample_data import assert_throwaway

DATED = {"company_daily", "sector_daily", "sector_performance", "sector_strength"}


def main():
    ap = argparse.ArgumentParser(description="Export the reporting views of a throwaway database as the dashboard's demo data")
    ap.add_argument("--years", type=float, default=3)
    ap.add_argument("--out", type=Path, default=SAMPLE_DIR)
    args = ap.parse_args()
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise SystemExit("DATABASE_URL is not set")
    assert_throwaway(url)
    src = DbSource(url)
    lo, hi = src.date_range()
    since = hi - timedelta(days=int(args.years * 365.25))
    args.out.mkdir(parents=True, exist_ok=True)
    for name in EXPORTS:
        df = src.table(name)
        if name in DATED:
            df = df[df["price_date"] >= str(since)]
        for col in df.select_dtypes("float").columns:
            df[col] = df[col].round(6)
        if "price_date" in df.columns:
            df["price_date"] = df["price_date"].dt.date
        df.to_csv(args.out / f"{name}.csv.gz", index=False, compression={"method": "gzip", "mtime": 0})
        print(f"{name}: {len(df)} rows")
    (args.out / "ABOUT.txt").write_text(
        f"Synthetic demo data (not real market prices): 25 tickers, {since} to {hi}. Generated by "
        f"scripts/load_sample_data.py and exported from the reporting views by scripts/build_demo_data.py.\n")


if __name__ == "__main__":
    main()
